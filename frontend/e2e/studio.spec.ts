import { test, expect } from "@playwright/test";
test("real Java workflow, multi-task recovery and identity isolation", async ({ page }) => {
  const errors: string[] = []; page.on("pageerror", error => errors.push(error.message));
  await page.goto("/templates");
  await expect(page.getByRole("link", { name: /萌宠画报/ })).toBeVisible();
  await page.getByRole("button", { name: "萌宠", exact: true }).click();
  await expect(page.locator(".template-card")).toHaveCount(2);
  await page.getByLabel("演示身份").selectOption("demo-a");
  await expect(page.getByLabel("演示身份")).toHaveValue("demo-a");
  await page.getByRole("link", { name: /萌宠画报/ }).click();
  const submit = page.getByRole("button", { name: "提交制作任务", exact: true });
  await expect(submit).toBeDisabled();
  const input = page.getByLabel("选择图片 1");
  await expect(input).toBeHidden();
  await input.setInputFiles({ name: "invalid.txt", mimeType: "text/plain", buffer: Buffer.from("invalid") });
  await expect(page.getByRole("alert").filter({ hasText: "请选择 JPEG" })).toBeVisible();
  const sample = await page.request.get("/files/samples/pet"); expect(sample.ok()).toBeTruthy();
  const image = { name: "pet.png", mimeType: "image/png", buffer: await sample.body() };
  const uploadBox = page.getByRole("button", { name: "上传图片 1", exact: true });
  await uploadBox.hover(); await expect(uploadBox.getByText("单击上传文件")).toHaveCSS("opacity", "1");
  const chooser = page.waitForEvent("filechooser"); await uploadBox.click(); await (await chooser).setFiles(image); await expect(submit).toBeEnabled();
  await page.getByRole("heading", { name: "上传你的图片" }).hover();
  await expect(page.getByRole("button", { name: "移除图片 1" })).toHaveCSS("opacity", "0");
  await page.getByRole("button", { name: "替换图片 1" }).hover();
  await expect(page.getByRole("button", { name: "移除图片 1" })).toHaveCSS("opacity", "1");
  await page.getByRole("button", { name: "移除图片 1" }).click(); await expect(submit).toBeDisabled();
  await input.setInputFiles(image); await expect(submit).toBeEnabled();
  await page.getByText("演示控制（可选）", { exact: true }).click();
  await page.getByLabel("使用自定义模拟参数").check();
  await page.getByLabel("素材检查耗时（毫秒）").fill("100");
  await page.getByLabel("模拟生成耗时（毫秒）").fill("5000");
  await page.getByLabel("结果整理耗时（毫秒）").fill("100");
  const accepted = page.waitForResponse(response => response.url().endsWith("/api/tasks") && response.request().method() === "POST");
  await submit.click(); const first = (await (await accepted).json()).taskId as string;
  await page.route(`**/api/tasks/${first}`, route => route.abort("failed"));
  await expect(submit).toBeEnabled();
  await page.getByLabel("失败阶段").selectOption("MOCK_GENERATION");
  await page.getByLabel("模拟生成耗时（毫秒）").fill("100");
  const accepted2 = page.waitForResponse(response => response.url().endsWith("/api/tasks") && response.request().method() === "POST");
  await submit.click(); const second = (await (await accepted2).json()).taskId as string; expect(second).not.toBe(first);
  await page.getByRole("link", { name: "我的作品", exact: true }).click();
  const firstCard = page.locator(`[data-task-id="${first}"]`); const secondCard = page.locator(`[data-task-id="${second}"]`);
  await expect(firstCard.getByText(/查询暂不可用/)).toBeVisible();
  await expect(firstCard.getByText("制作失败", { exact: true })).toHaveCount(0);
  await page.unroute(`**/api/tasks/${first}`);
  await firstCard.getByRole("button", { name: "恢复查询" }).click();
  await expect(firstCard.getByText("制作成功", { exact: true })).toBeVisible({ timeout: 20000 });
  await expect(secondCard.getByText("制作失败", { exact: true })).toBeVisible({ timeout: 20000 });
  await page.reload();
  await expect(page.locator(`[data-task-id="${first}"]`).getByText("制作成功", { exact: true })).toBeVisible();
  await page.locator(`[data-task-id="${first}"]`).getByRole("button", { name: /预览.*结果/ }).click();
  await expect(page.getByRole("dialog")).toBeVisible(); await page.getByRole("button", { name: "关闭预览" }).click();
  await page.getByLabel("演示身份").selectOption("demo-b");
  await expect(page.getByLabel("演示身份")).toHaveValue("demo-b");
  await expect(page.locator(`[data-task-id="${first}"]`)).toHaveCount(0);
  expect((await page.request.get(`/api/tasks/${first}`)).status()).toBe(404);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto("/templates"); await expect(page.locator(".template-card").first()).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
  await page.screenshot({ path: "test-results/templates-mobile.png", fullPage: true });
  expect(errors).toEqual([]);
});

test("two-image template and refresh while running; terminal tasks stop polling", async ({ page }) => {
  await page.goto("/templates/demo-postcard");
  await page.getByLabel("演示身份").selectOption("demo-a");
  const submit = page.getByRole("button", { name: "提交制作任务", exact: true });
  const sample = await page.request.get("/files/samples/postcard");
  const file = { name: "sample.png", mimeType: "image/png", buffer: await sample.body() };
  await page.getByLabel("选择图片 1").setInputFiles(file); await expect(submit).toBeDisabled();
  await page.getByLabel("选择图片 2").setInputFiles(file); await expect(submit).toBeEnabled();
  await page.getByText("演示控制（可选）", { exact: true }).click(); await page.getByLabel("使用自定义模拟参数").check();
  await page.getByLabel("模拟生成耗时（毫秒）").fill("6000");
  const accepted = page.waitForResponse(response => response.url().endsWith("/api/tasks") && response.request().method() === "POST");
  await submit.click(); const id = (await (await accepted).json()).taskId as string;
  await page.goto(`/tasks/${id}`); await page.reload();
  const card = page.locator(`[data-task-id="${id}"]`);
  await expect(card.getByText("处理中", { exact: true })).toBeVisible();
  await expect(card.getByText("制作成功", { exact: true })).toBeVisible({ timeout: 25000 });
  let queries = 0; page.on("request", request => { if (request.url().endsWith(`/api/tasks/${id}`)) queries++; });
  await page.waitForTimeout(2000); expect(queries).toBe(0);
  await page.goto("/templates/does-not-exist"); await expect(page.getByRole("heading", { name: "模板不存在" })).toBeVisible();
});
